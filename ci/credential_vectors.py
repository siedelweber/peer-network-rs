"""Independent public SCRAM vectors using Python's OpenSSL-backed primitives."""
import base64
import hashlib
import hmac
from pathlib import Path


def render():
    """Render fixture Rust; never import or execute a workspace implementation."""
    cases = [
        (b"pencil", base64.b64decode("W22ZaJ0SNY7soEsUEjb6gQ=="), 4096),
        (b"public-credential-vector", bytes(range(16)), 600000),
        (b"another-public-vector", bytes(reversed(range(16))), 600000),
    ]
    text = "// Generated by ci/credential_vectors.py; public fixture inputs only.\n"
    text += "// The first input is RFC 7677 section 3; intermediate keys are independently computed here.\n"
    text += "use super::Vector;\n\npub(super) const VECTORS: &[Vector] = &[\n"
    for password, salt, iterations in cases:
        salted = hashlib.pbkdf2_hmac("sha256", password, salt, iterations, 32)
        client = hmac.digest(salted, b"Client Key", "sha256")
        server = hmac.digest(salted, b"Server Key", "sha256")
        stored = hashlib.sha256(client).digest()
        verifier = b"SCRAM-SHA-256$" + str(iterations).encode() + b":" + base64.b64encode(salt) + b"$" + base64.b64encode(stored) + b":" + base64.b64encode(server)
        text += "    Vector {\n"
        text += '        password: b"' + password.decode() + '",\n'
        text += "        iterations: " + ("600_000" if iterations == 600000 else str(iterations)) + ",\n"
        for name, value in (("salt", salt), ("salted", salted), ("client", client), ("stored", stored), ("server", server)):
            text += "        " + name + ': *b"' + "".join(f"\\x{byte:02x}" for byte in value) + '",\n'
        text += '        verifier: b"' + verifier.decode() + '",\n'
        text += "    },\n"
    return text + "];\n"


def check(root):
    """Refuse any changed operand or expected output, including verifier framing."""
    expected = render()
    actual = (root / "packages/credential-derivation/src/tests/vectors.rs").read_text()
    if actual != expected:
        raise ValueError("credential vectors differ from independent reconstruction")


if __name__ == "__main__":
    import sys
    root = Path(__file__).resolve().parent.parent
    if sys.argv[1:] == ["--write"]:
        (root / "packages/credential-derivation/src/tests/vectors.rs").write_text(render())
    else:
        check(root)
